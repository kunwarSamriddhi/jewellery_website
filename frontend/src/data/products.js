export const getProductById = (id) => {
  return products.find((p) => p.id === id);
};

export const getFeaturedProducts = () => {
  return products.filter((p) => p.isFeatured);
};

export const getNewArrivals = () => {
  return products.filter((p) => p.isNewArrival);
};

export const getArtificialProducts = () => {
  return products.filter((p) => p.jewelleryType === "artificial");
};

export const getPreciousProducts = () => {
  return products.filter((p) => p.jewelleryType === "precious");
};

export const getProductsByCategory = (categorySlug) => {
  if (!categorySlug || categorySlug.toLowerCase() === "all") return products;
  return products.filter(
    (p) => p.category.trim().toLowerCase() === categorySlug.trim().toLowerCase()
  );
};
